export const COLORMAP_MODEL = 'gfs';
export const COLORMAP_RUN_ID = '20260728_12z';
export const COLORMAP_VARIABLE = 'tmp2m';

/** Web-mercator bbox centered on the CONUS default center (-98.58, 39.83). */
export const COLORMAP_BBOX = [-11273875, 4742782, -10673875, 4942782];
export const COLORMAP_VIEW = { lat: 39.83, lon: -98.58, zoom: 6 };

/**
 * 3x1 grid; uint16 encode (v + 100) * 10 with scale 0.1 / offset -100.
 * Each forecast hour shifts the band by +2 °F so a frame step is
 * pixel-confirmable: FH1 has rendered exactly when the sampled cells change.
 */
export const COLORMAP_BAND_VALUES_BY_FH: Record<number, number[]> = {
  0: [72, 82, 92],
  1: [74, 84, 94],
  2: [76, 86, 96],
};
export const COLORMAP_BAND_VALUES_F = COLORMAP_BAND_VALUES_BY_FH[0];

export function frameBinaryForHour(fh: number): Uint16Array {
  const values = COLORMAP_BAND_VALUES_BY_FH[fh] ?? COLORMAP_BAND_VALUES_BY_FH[0];
  return new Uint16Array(values.map((v) => (v + 100) * 10));
}

export function approvedLegendStops(): Array<[number, string]> {
  return TMP2M_APPROVED_LEGEND_ENTRIES.map((entry) => [entry.value, entry.color]);
}

