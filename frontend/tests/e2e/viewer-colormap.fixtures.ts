const FRAME_HOURS = [0, 1, 2];

function validTime(fh: number): string {
  return `2026-07-28T${String(12 + fh).padStart(2, '0')}:00:00Z`;
}

function manifestPayload() {
  return {
    model: COLORMAP_MODEL,
    run: COLORMAP_RUN_ID,
    region: 'conus',
    variables: {
      [COLORMAP_VARIABLE]: {
        display_name: 'Temperature 2m',
        kind: 'continuous',
        units: 'F',
        frames: FRAME_HOURS.map((fh) => ({ fh, valid_time: validTime(fh) })),
      },
      // Makes productAvailability.p90 true so the Statistic control shows
      // both options (the trigger renders only with >1 available product).
      tmp2m_p90: {
        display_name: 'Temperature 2m · 90th %ile',
        kind: 'continuous',
        units: 'F',
        frames: FRAME_HOURS.map((fh) => ({ fh, valid_time: validTime(fh) })),
      },
    },
  };
}

function framesPayload() {
  return FRAME_HOURS.map((fh) => ({
    fh,
    has_cog: true,
    run: COLORMAP_RUN_ID,
    valid_time: validTime(fh),
    meta: {
      meta: {
        valid_time: validTime(fh),
        units: 'F',
        kind: 'continuous',
        display_name: 'Temperature 2m',
        // Sidecar legend carrying the approved Phase 3 anchors — the exact
        // shape buildLegend()'s legend_stops fallback consumes.
        legend_stops: approvedLegendStops(),
      },
    },
  }));
}

function gridManifestPayload() {
  return {
    manifest_version: 1,
    subtype: 'grid',
    model: COLORMAP_MODEL,
    run: COLORMAP_RUN_ID,
    var: COLORMAP_VARIABLE,
    projection: 'EPSG:3857',
    bbox: COLORMAP_BBOX,
    grid: {
      width: 3,
      height: 1,
      dtype: 'uint16',
      endianness: 'little',
      scale: 0.1,
      offset: -100.0,
      nodata: 65535,
      units: 'F',
    },
    palette: {
      color_map_id: 'tmp2m',
      kind: 'continuous',
      transparent_below_min: null,
      transparent_zero: false,
    },
    lods: [
      {
        level: 0,
        width: 3,
        height: 1,
        frames: FRAME_HOURS.map((fh) => ({
          fh,
          file: `fh${String(fh).padStart(3, '0')}.l0.u16.bin`,
          valid_time: validTime(fh),
          url: `/api/v4/grid/${COLORMAP_MODEL}/${COLORMAP_RUN_ID}/${COLORMAP_VARIABLE}/fh${String(fh).padStart(3, '0')}.l0.u16.bin?v=${COLORMAP_RUN_ID}-${COLORMAP_VARIABLE}-${fh}`,
        })),
      },
    ],
  };
}

